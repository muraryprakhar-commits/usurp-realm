#!/usr/bin/env node
/* Builds the emblem artwork table (ART) inside crest-core.js from the sources in this folder.
   Run from the repo root after editing any emblem:   node tools/emblems/assemble.js

   Sources
   - beasts.js, heads.js, symbols.js: original drawings made for Crest Studio with kit.js (ours, no third-party rights).
   - armoria-cc0/*.svg: charges by Azgaar and contributors from the Armoria project, each file marked CC0 1.0
     (public domain dedication) in its own <metadata>. Only CC0 files may be added to that folder; the script refuses others.

   Every emblem is fitted into the shield's charge area (shield units, 100 x 122) and stored as
   [scale, x, y, outline width, backing markup, art markup]. crest-core.js draws the backing in dark ink with a thick
   stroke (the outer outline), then the art in the chosen tincture on top. */
const fs = require('fs'), path = require('path');
const { Resvg } = require('@resvg/resvg-js');
const { make } = require('./make.js');
const HERE = __dirname, CORE = path.join(HERE, '..', '..', 'crest-core.js');
const ST = '#1a0e05';

// CC0 imports: id -> [file, box w, box h, centre y, fill-layer line width in shield units]
const IMPORTS = {
  fleur: ['fleurDeLis', 50, 62, 60, 0.35], cross: ['crossPattee', 54, 56, 60, 0.35], maltese: ['crossMaltese', 54, 56, 60, 0.35],
  fleury: ['crossFleury', 56, 58, 60, 0.35], triquetra: ['crossTriquetra', 56, 52, 60, 0.4], heart: ['heart', 46, 46, 60, 0.35],
  sun: ['sun', 58, 58, 60, 0.3], compass: ['compassRose', 58, 58, 60, 0.3], scales: ['scale', 56, 60, 60, 0.3],
  dividers: ['drawingCompass', 44, 62, 60, 0.35], laurel: ['laurelWreath2', 58, 52, 60, 0.3], anchor: ['anchor', 50, 62, 60, 0.3],
  caduceus: ['caduceus', 52, 62, 60, 0.3],
};
function bbox(inner) {
  return new Resvg(`<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" viewBox="0 0 300 300" width="300" height="300"><g fill="#000">${inner}</g></svg>`).getBBox();
}
function importCC0(id, [file, W, H, cy, line]) {
  const src = fs.readFileSync(path.join(HERE, 'armoria-cc0', file + '.svg'), 'utf8');
  if (!/license="https:\/\/creativecommons\.org\/publicdomain\/zero\/1\.0"/.test(src)) throw new Error(`${file} is not marked CC0`);
  let inner = src.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').replace(/<metadata[^>]*\/>/g, '')
    .replace(/\s+id="[^"]*"/g, '').replace(/\s+class="[^"]*"/g, '')
    .replace(/fill="(#000|#000000|black)"/g, `fill="${ST}"`).replace(/stroke="(#000|#000000|black)"/g, `stroke="${ST}"`)
    .replace(/\s+fill="(#d7374a|#d6d6d6)"/g, '').replace(/>\s+</g, '><').trim();
  const b = bbox(inner), s = Math.min(W / b.width, H / b.height), n = v => +v.toFixed(3);
  const tx = 50 - s * (b.x + b.width / 2), ty = cy - s * (b.y + b.height / 2);
  const back = inner.replace(/\s(stroke|stroke-width|stroke-opacity|fill-opacity)="[^"]*"/g, '').replace(/\sfill="(?!none)[^"]*"/g, '');
  const art = `<g stroke="${ST}" stroke-width="${n(line / s)}">${inner.replace(/\sstroke-width="[^"]*"/g, '')}</g>`;
  return { m: [n(s), n(tx), n(ty)], ow: n(2 / s), back, art };
}
const out = {};
for (const file of ['beasts.js', 'heads.js', 'symbols.js']) {
  const defs = require(path.join(HERE, file));
  for (const [id, v] of Object.entries(defs)) out[id] = make(v.els, v.o);
}
for (const [id, spec] of Object.entries(IMPORTS)) out[id] = importCC0(id, spec);
// single quotes inside the markup keep the generated JS free of escapes
const q = s => JSON.stringify(s.replace(/"/g, "'"));
const lines = Object.entries(out).map(([id, e]) => `  ${id}: [${e.m.join(', ')}, ${e.ow}, ${q(e.back)}, ${q(e.art)}],`);
const block = `/* ART:BEGIN (generated by tools/emblems/assemble.js, do not edit by hand) */\nconst ART = {\n${lines.join('\n')}\n};\n/* ART:END */`;
let core = fs.readFileSync(CORE, 'utf8');
if (!core.includes('/* ART:BEGIN')) throw new Error('crest-core.js has no ART:BEGIN marker');
core = core.replace(/\/\* ART:BEGIN[\s\S]*?\/\* ART:END \*\//, block);
fs.writeFileSync(CORE, core);
const bytes = lines.reduce((a, l) => a + l.length, 0);
console.log(`ART: ${Object.keys(out).length} emblems, ${(bytes / 1024).toFixed(1)} KB written into crest-core.js`);
